// The data pack: the game files the app reads (portraits, artifact art, skill
// and effect text, cooldowns, the screenshot import's references), kept
// outside this repo and copied into the ignored src/pack/ by npm run data.

import { execFileSync } from 'node:child_process'
import {
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { createServer } from 'vite'

import { outfitHero } from '../../src/lib/characters/outfit.ts'
import { FRAME_NAMES } from '../../src/lib/import/card/frames.ts'
import { SKILL_LOCALES } from '../../src/lib/types/i18n.ts'

const SKILL = 'text/skill'
// The pinned version a download holds; a copy from a local folder has none.
const MARKER = '.version'

// Seasonal text is left out: a season ships before its text, and git keeps no
// empty folder.
const PACK_FOLDERS = [
  'images/character',
  'images/artifact',
  'images/seasonal/artifact',
  'images/seasonal/phantimal',
  'screenshot-import',
  'text/skill',
  'text/artifact',
]

// The files the app imports directly. Without a pack they are written empty,
// so dev, the type check and the tools that load the app's modules still run.
const STAND_INS: Record<string, string> = {
  'text/skill/numbers.json': '{}\n',
  'screenshot-import/hero-icons.json': '{ "icons": [] }\n',
}

const bundleFile = `// Generated by npm run data. Importing this module loads every skill text
// file in this folder as one chunk; see loadSkillLocale() in src/utils/dataLoader.ts.
import type { SkillLocaleFile } from '@/lib/types/skill'

const modules = import.meta.glob<SkillLocaleFile>('./*.json', {
  eager: true,
  import: 'default',
})

const dict: Record<string, SkillLocaleFile> = {}
for (const [path, file] of Object.entries(modules)) {
  dict[path.slice(2, -'.json'.length)] = file
}

export default dict
`

const bundlePath = (code: string): string => `${SKILL}/${code}/index.ts`

const isGenerated = (path: string): boolean =>
  SKILL_LOCALES.some(({ code }) => path === bundlePath(code))

// Every file under dir, relative to it, dotfiles (.DS_Store) left out.
function listFiles(dir: string, base = dir): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.')) return []
    const path = join(dir, entry.name)
    return entry.isDirectory() ? listFiles(path, base) : [relative(base, path)]
  })
}

function pruneEmptyFolders(dir: string): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const path = join(dir, entry.name)
    pruneEmptyFolders(path)
    if (readdirSync(path).length === 0) rmdirSync(path)
  }
}

const sameFile = (a: string, b: string): boolean =>
  existsSync(b) && statSync(a).size === statSync(b).size && readFileSync(a).equals(readFileSync(b))

function writeIfChanged(path: string, text: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  return true
}

const jsonNames = (dir: string): string[] =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith('.json'))
        .map((f) => f.slice(0, -'.json'.length))
        .sort()
    : []

// Underscore files are per-language data, not heroes.
const heroFiles = (dir: string): string[] => jsonNames(dir).filter((name) => !name.startsWith('_'))

/** Makes dest a copy of source and returns how many files changed. Files that
 * already match are left alone, so a running dev server reloads only what
 * changed, and the files npm run data generates stay while the source holds
 * their language. */
export function mirror(source: string, dest: string): number {
  const wanted = new Set(listFiles(source))
  let changed = 0
  for (const path of listFiles(dest)) {
    if (wanted.has(path) || (isGenerated(path) && existsSync(join(source, dirname(path))))) continue
    rmSync(join(dest, path))
    changed++
  }
  for (const path of wanted) {
    const from = join(source, path)
    const to = join(dest, path)
    if (sameFile(from, to)) continue
    mkdirSync(dirname(to), { recursive: true })
    copyFileSync(from, to)
    changed++
  }
  if (existsSync(dest)) pruneEmptyFolders(dest)
  return changed
}

/** Writes the skill bundling files, and returns how many changed. A bundling
 * file goes only where the pack holds the language, so it never stands in for
 * missing text. */
export function writeGenerated(pack: string): number {
  let changed = 0
  for (const { code } of SKILL_LOCALES) {
    if (
      existsSync(join(pack, SKILL, code)) &&
      writeIfChanged(join(pack, bundlePath(code)), bundleFile)
    )
      changed++
  }
  return changed
}

/** Writes the empty stand-ins where the pack lacks them, and returns how many it wrote. */
export function writeStandIns(pack: string): number {
  let written = 0
  for (const [path, text] of Object.entries(STAND_INS)) {
    if (existsSync(join(pack, path))) continue
    writeIfChanged(join(pack, path), text)
    written++
  }
  return written
}

const hasFile = (pack: string, path: string): boolean => {
  const file = join(pack, path)
  return (
    existsSync(file) &&
    (STAND_INS[path] === undefined || readFileSync(file, 'utf8') !== STAND_INS[path])
  )
}

/** The pictures the skill code draws companions with. The skills register
 * through import.meta.glob, so they load through Vite. */
export async function companionPictures(root: string): Promise<string[]> {
  const vite = await createServer({
    configFile: false,
    root,
    resolve: { alias: { '@': join(root, 'src') } },
    server: { middlewareMode: true, hmr: false, ws: false },
    appType: 'custom',
    logLevel: 'error',
    optimizeDeps: { noDiscovery: true, include: [] },
  })
  try {
    const { companionImages } = (await vite.ssrLoadModule('/src/lib/characters/companion.ts')) as {
      companionImages: () => { image: string }[]
    }
    return companionImages().map(({ image }) => image)
  } finally {
    await vite.close()
  }
}

/** What stops a build: the pack lacking what the app reads, or out of step
 * with this repo's own files. New content whose text or portrait lags behind
 * the feed is only a note: a hero with no portrait or skill text yet, and a
 * seasonal unit with no text yet. A seasonal unit's pictures come with its
 * season, so a missing one is what a season shipped without a new pin looks
 * like, and stops the build. A companion picture the pack lacks is a note,
 * since the companion is still drawn, without a picture. */
export function packProblems(
  pack: string,
  root: string,
  companions: readonly string[],
): { problems: string[]; notes: string[] } {
  const problems: string[] = []
  const notes: string[] = []
  for (const folder of PACK_FOLDERS) {
    if (!existsSync(join(pack, folder))) problems.push(`the pack has no ${folder} folder`)
  }
  for (const file of [
    ...Object.keys(STAND_INS),
    'screenshot-import/replay-arena.png',
    ...FRAME_NAMES.map((name) => `screenshot-import/frame-${name}.png`),
  ]) {
    if (!hasFile(pack, file)) problems.push(`the pack has no ${file}`)
  }

  const english = heroFiles(join(pack, SKILL, 'en'))
  for (const { code } of SKILL_LOCALES) {
    const heroes = heroFiles(join(pack, SKILL, code))
    if (heroes.length === 0) problems.push(`the pack has no ${code} skill text`)
    else if (heroes.join() !== english.join()) {
      problems.push(`the ${code} skill text covers other heroes than the English`)
    }
  }

  const sets = [
    ['src/data/artifact', 'images/artifact', 'text/artifact', problems],
    ['src/data/seasonal/artifact', 'images/seasonal/artifact', 'text/seasonal/artifact', notes],
    ['src/data/seasonal/phantimal', 'images/seasonal/phantimal', 'text/seasonal/phantimal', notes],
  ] as const
  for (const [data, images, text, missingText] of sets) {
    for (const name of jsonNames(join(root, data))) {
      if (!existsSync(join(pack, images, `${name}.png`)))
        problems.push(`${name} has no picture in the pack`)
      if (!existsSync(join(pack, text, `${name}.json`)))
        missingText.push(`${name} has no text in the pack`)
    }
  }

  const heroes = jsonNames(join(root, 'src/data/character'))
  const known = new Set(heroes)
  const withText = new Set(english)
  const portraits = new Set(
    listFiles(join(pack, 'images/character'))
      .filter((f) => f.endsWith('.png'))
      .map((f) => f.slice(0, -'.png'.length))
      .filter((name) => outfitHero(name) === null),
  )
  for (const slug of english) {
    if (!known.has(slug)) problems.push(`the pack has skill text for ${slug}, who has no hero file`)
  }
  // Heroes and phantimals share one picture list keyed by name.
  for (const slug of jsonNames(join(root, 'src/data/seasonal/phantimal'))) {
    if (known.has(slug)) problems.push(`${slug} is both a hero and a phantimal`)
  }
  for (const slug of heroes) {
    if (!portraits.has(slug)) notes.push(`${slug} has no portrait yet`)
    if (!withText.has(slug)) notes.push(`${slug} has no skill text yet`)
  }
  const pictures = ['images/character', 'images/seasonal/phantimal']
  for (const name of companions) {
    if (!pictures.some((folder) => existsSync(join(pack, folder, `${name}.png`))))
      notes.push(`the companion picture ${name} is not in the pack`)
  }
  return { problems, notes }
}

const git = (dir: string, ...args: string[]): string =>
  execFileSync('git', ['-C', dir, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim()

const unsaved = (dir: string): number =>
  git(dir, 'status', '--porcelain', '--untracked-files=all', '--', '.').split('\n').filter(Boolean)
    .length

const files = (count: number): string =>
  `${count} uncommitted or untracked ${count === 1 ? 'file' : 'files'}`

/** The commit the pack folder is at, for data.lock. */
export const packCommit = (dir: string): string => git(dir, 'rev-parse', 'HEAD')

/** Why the pack folder's current commit can't be pinned, or null when it can:
 * the build downloads the pin from the remote, so it must name a pushed commit
 * that holds every file of the folder. */
export function pinProblem(dir: string): string | null {
  const count = unsaved(dir)
  if (count) return `the pack folder has ${files(count)}; commit and push them first`
  if (!git(dir, 'branch', '-r', '--contains', packCommit(dir))) {
    return 'the pack folder holds commits that are not pushed yet, so the host could not build them'
  }
  return null
}

/** One line when the pack folder differs from the pin, or null. Commits that
 * leave the pack folder alone don't count. */
export function pinNotice(dir: string, pin: string | null): string | null {
  try {
    packCommit(dir)
  } catch {
    return null
  }
  if (!pin) return 'no pin yet; npm run data:pin writes one'
  let moved = false
  try {
    git(dir, 'diff', '--quiet', pin, 'HEAD', '--', '.')
  } catch {
    moved = true
  }
  const count = unsaved(dir)
  if (!moved && !count) return null
  return `your pack folder differs from the pinned version${count ? ` (${files(count)})` : ''}`
}

export const readMarker = (pack: string): string | null =>
  existsSync(join(pack, MARKER)) ? readFileSync(join(pack, MARKER), 'utf8').trim() : null

export const dropMarker = (pack: string): void => rmSync(join(pack, MARKER), { force: true })

/** A download failure whose message is safe for a public build log. */
export class DownloadError extends Error {}

/** Downloads the pinned snapshot of the repo that holds the pack and replaces
 * the copy with the folder at `path` inside it. The copy changes only once
 * the new one is complete. */
export async function download(
  url: string,
  token: string,
  path: string,
  version: string,
  pack: string,
  staging: string,
): Promise<void> {
  const work = mkdtempSync(join(tmpdir(), 'pack-'))
  try {
    let response: Response
    try {
      response = await fetch(`${url}/${version}`, {
        headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
      })
    } catch {
      throw new DownloadError('the download failed')
    }
    if (!response.ok) throw new DownloadError(`the download failed (HTTP ${response.status})`)
    const archive = join(work, 'pack.tar.gz')
    writeFileSync(archive, Buffer.from(await response.arrayBuffer()))
    try {
      execFileSync('tar', ['-xzf', archive, '-C', work], { stdio: 'ignore' })
    } catch {
      throw new DownloadError('the download could not be unpacked')
    }
    const top = readdirSync(work, { withFileTypes: true }).filter((entry) => entry.isDirectory())
    const source = top.length === 1 ? join(work, top[0]!.name, path) : null
    if (!source || !existsSync(source))
      throw new DownloadError('the download lacks the pack folder')

    const next = join(staging, 'next')
    const old = join(staging, 'old')
    rmSync(staging, { recursive: true, force: true })
    mkdirSync(staging, { recursive: true })
    cpSync(source, next, { recursive: true })
    if (existsSync(pack)) renameSync(pack, old)
    renameSync(next, pack)
    writeFileSync(join(pack, MARKER), `${version}\n`)
    rmSync(staging, { recursive: true, force: true })
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
}
