  <p class="formula">E(s) = min<sub>a</sub> [ c(a) + Σ<sub>o</sub> P(o | s, a) × E(s′) ]</p>
  <p>
    E(s)는 상태 s에서 목표를 이룰 때까지 평균적으로 쓰는 휘장입니다. 여기서 상태는 아직 필요한 장수,
    보이는 카드, 잠근 카드의 출처에 대해 알고 있는 내용이며, 가진 휘장은 포함하지 않습니다. c(a)는
    한 수의 비용으로, 새로고침은 휘장 {{ f.reroll }}개, 구매는 그 가격입니다. 팩에서 나온 영웅을
    팔아 얻는 휘장은 결과마다 따로 뺍니다. 목표를 이루면 E는 0입니다.
  </p>
  <p>
    잠금 없이 새로고침하면 똑같은 상태로 돌아올 수 있으므로 E(s)가 식의 양쪽에 모두 나옵니다. 답은
    모든 상태의 식이 동시에 성립하는 값입니다. 잠금이 없고 카드 한 장만 찾는 경우(나올 확률 q, 가격
    p)에는 위의 공식이 됩니다.
  </p>
  <p class="formula">E = {{ f.reroll }} ÷ q + p</p>
  <p>
    무작위 레전드 영웅에서 원하는 영웅이 나오는 것은 {{ f.poolSize }}번에 한 번이므로, 한 번 맞히는
    데 평균 휘장 {{ f.legendaryPrice }} × {{ f.poolSize }} =
    {{ (f.legendaryPrice * f.poolSize).toLocaleString('en') }}개가 듭니다. 영웅 한 명을 찾을 때 최소
    휘장은 이 상품을 고르지 않습니다.
  </p>
  <p>
    두 답은 다를 수 있습니다. 지금 카드 한 장을 사는 것이 이번 라운드의 최고 확률이어도, 휘장을 아껴
    다음 상점에서 쓰는 편이 평균 비용은 더 적을 수 있습니다. 평균은 평균일 뿐이어서, 운이 나쁘면
    실제 지출은 훨씬 클 수 있습니다.
  </p>

  <h2>이번 라운드를 멈출 때</h2>
  <p>
    명예의 결투는 여러 라운드에 걸쳐 진행되고, 남긴 휘장은 이후 상점에서 씁니다. 최고 확률은 이번
    라운드만 봅니다. 최소 휘장은 목표까지의 전체 과정을 봅니다. 휘장에 제한이 없다면 어떤 계획이든
    결국 목표에 닿으므로, 평균 지출이 가장 적은 계획이 가장 좋습니다.
  </p>
  <p>
    휘장이 무한하다는 가정은 선택을 비교하기 위한 것일 뿐입니다. 실제로는 가진 휘장으로만
    움직이므로, 이번 라운드에 목표를 이룰 수 없게 되면 더 쓰기보다 멈추는 편이 낫습니다. 라운드의 첫
    상점은 잠기지 않은 카드를 무료로 다시 뽑으므로, 멈추면 새로고침 휘장 없이 새 상점을 볼 수
    있습니다.
  </p>
  <p>
    계산기는 가장 저렴한 수를 치를 수 없을 때, 그 수로는 이번 라운드에 완성할 가능성이 없을 때, 또는
    다음 라운드에 상점 레벨이 오르고 기다리는 편이 새로고침 한 번 값 넘게 저렴할 때 멈추라고 합니다.
  </p>
  <p>
    멈추기 전에 카드를 잠글지 살지도 같은 식으로 판단합니다. 잠그면 좋은 카드를 다음 라운드까지 남길
    수 있지만 그 출처가 다시 뽑지 못합니다. 사면 출처가 풀리지만, 나중에 더 좋은 카드가 나와도
    휘장은 이미 쓴 것입니다. 다음 라운드에 상점 레벨이 오르면 출처가 내는 상품이 달라지므로,
    잠금이나 구매의 가치는 그 레벨의 목록으로 판단해야 합니다.
  </p>
  <p>
    휘장이 넉넉하면 최고 확률과 최소 휘장은 대개 같은 수를 고릅니다. 휘장이 빠듯하면 달라질 수
    있습니다. 이번 라운드에 두 장을 채울 방법이 영웅 {{ f.draws }}명짜리 팩뿐이라면, 최고 확률은 그
    팩을 사고, 최소 휘장은 비효율적인 팩을 사지 않고 멈춰 이후 라운드에서 영웅 카드를 찾습니다.
  </p>

  <h2>규칙과 관찰</h2>
  <p>
    규칙은 모든 경우에 성립하는 비교입니다. 한 선택이 다른 선택보다 나쁜 경우가 없다면 다른 선택은
    따져 볼 필요가 없습니다. 관찰은 조건이 붙은 비교로, 평균 휘장이나 확률을 나란히 놓고 얻은
    것입니다. 조건이 맞을 때는 판단의 기준이 되지만 조건이 다르면 결론이 뒤집힐 수 있으므로 계산을
    대신하지는 못합니다.
  </p>

  <h3>규칙 1. 어차피 살 잠긴 카드는 지금 산다</h3>
  <p>
    잠긴 카드는 지금 사든 나중에 사든 값이 같고, 산 카드의 자리는 다음 새로고침에서 다시 뽑히므로
    기회가 한 번 늘어납니다. 잠금이 구매보다 나은 경우는 나중에 그 카드를 포기하고 더 싸게 목표를
    이룰 가능성이 있을 때뿐입니다. 잠금의 가치는 포기할 수 있다는 데 있고, 그 가치가 추가로 뽑는 한
    자리보다 큰지는 계산으로 정합니다.
  </p>

  <h3>규칙 2. 한 상점에서 팩과 확실한 카드를 둘 다 살 것이라면 팩을 먼저 연다</h3>
  <p>
    한 상점 안에서는 구매 순서가 가격을 바꾸지 않고, 카드는 다음 새로고침까지 남아 있습니다. 결과를
    알 수 없는 팩을 먼저 열면 결과를 보고 나머지 구매를 정할 수 있습니다. 팩에서 목표 영웅이 나오면
    확실한 카드는 사지 않아도 됩니다. 팩을 먼저 여는 쪽이 더 나쁜 경우는 없습니다.
  </p>

  <h3>관찰 1. 사도 초과하지 않는다면 잠그지 말고 산다</h3>
  <p>
    영웅 카드는 한 장짜리든 두 장짜리든 한 장에 휘장 {{ f.heroPrice }}개입니다. 잠금은 보통 초과
    구매를 피하려고 씁니다. 두 장이 더 필요할 때 한 장짜리 영웅 카드를 사면, 나중에 두 장짜리 영웅
    카드가 나왔을 때 세 장 값을 치르게 됩니다. 한 장짜리 영웅 카드를 잠가 두면 두 장짜리 영웅 카드를
    사고 잠근 카드를 포기할 수 있습니다.
  </p>
  <p>
    초과는 남은 장수가 홀수이고 두 장짜리 영웅 카드로 채울 때만 생깁니다. 두 장짜리 영웅 카드를 사도
    남은 장수의 홀짝은 바뀌지 않고, 남은 장수가 홀수일 때 한 장짜리 영웅 카드를 사면 짝수가 되어
    위험이 사라집니다. 이런 경우에는 그 카드 없이 완성하는 어떤 방법도 그 카드를 산 뒤에 더 비싸지
    않게 그대로 완성되므로, 포기할 이유가 없습니다.
  </p>
  <p>
    한 번에 여러 장을 주는 상품이 나올 수 있다면, 예를 들어 {{ f.legendaryCopies }}장을 주는 무작위
    레전드 영웅이 있다면, 한 장당 가격이 같지 않으므로 이 관찰은 성립하지 않습니다.
  </p>

  <h3>관찰 2. 두 장이 필요할 때 휘장이 빠듯하면 한 장짜리 영웅 카드를 잠그고, 넉넉하면 산다</h3>
  <p>
    초과 구매가 가장 크게 작용하는 경우입니다. 휘장이 B개이고 한 장짜리 영웅 카드가 보인다고 합시다.
    그 카드를 잠그면 어떻게 완성하든 휘장 {{ f.pairPrice }}개가 듭니다. 한 장짜리 영웅 카드가 하나
    더 나와 잠근 카드와 함께 사거나, 잠근 카드를 포기하고 두 장짜리 영웅 카드를 사는 경우입니다.
    남는 새로고침은 (B − {{ f.pairPrice }}) ÷ {{ f.reroll }}회입니다.
  </p>
  <p>
    바로 사면 마지막 한 장이 한 장짜리 영웅 카드로 올 때는 남는 새로고침이 같지만, 두 장짜리 영웅
    카드로 올 때는 (B − {{ f.heroPrice + f.pairPrice }}) ÷ {{ f.reroll }}회로
    {{ f.heroPrice / f.reroll }}회 적습니다. 대신 산 카드의 자리가 새로고침마다 다시 뽑힙니다.
    휘장이 적으면 이 {{ f.heroPrice / f.reroll }}회가 전체에서 큰 몫이므로 잠그는 편이 낫습니다.
    휘장이 많으면 대개 그 전에 목표를 이루므로 한 자리를 더 뽑는 가치가 더 큽니다.
  </p>
  <p>
    Toto의 계산기에 따르면 상점 레벨 {{ f.levels.length }}, 풀이 영웅 {{ f.poolSize }}명 전체일 때
    경계는 휘장 약 60개입니다. 그보다 적으면 잠금이, 많으면 구매가 낫고, 경계 근처에서는 둘의 차이가
    1%p 미만입니다. 그보다 낮은 레벨에서는 두 장짜리 영웅 카드가 드물어 휘장이 적어도 구매가
    낫습니다. 이것은 이번 라운드에 목표를 이룰 확률을 비교한 것이며, 이번 라운드에 완성하지 못했을
    때 산 카드를 가지고 있는 가치는 넣지 않았습니다.
  </p>

  <h3>관찰 3. 한 장이 필요한데 그 영웅의 두 장짜리 영웅 카드가 나오면 산다</h3>
  <p>
    최소 휘장 기준으로 다른 선택은 두 장짜리 영웅 카드(휘장 {{ f.pairPrice }}개)를 잠그고 휘장
    {{ f.heroPrice }}개인 한 장짜리 영웅 카드가 나올 때까지 새로고침하는 것입니다. 새로고침 한 번에
    그 카드가 나올 확률이 p라면 약 1 ÷ p회가 필요하므로, 다음 조건에서는 기다리는 쪽의 평균 비용이
    더 큽니다.
  </p>
  <p class="formula">
    {{ f.heroPrice }} + {{ f.reroll }} ÷ p ≥ {{ f.pairPrice }}, 즉 p ≤
    {{ percent(f.pairBreakEven) }}
  </p>
  <p>
    새로고침할 때마다 같은 선택 앞에 서게 되므로, 몇 번 새로고침해 본 뒤 사는 방법이 둘 중 나은 쪽을
    이길 수는 없습니다. 관찰 4에 따라 팩은 이 비교를 바꾸지 않습니다. 두 장짜리 영웅 카드가 나오는
    상점 레벨에서 풀이 영웅 {{ f.poolSize }}명 전체일 때 p는 {{ percent(f.pairSingle.low) }}에서
    {{ percent(f.pairSingle.high) }} 사이이므로 바로 사는 편이 낫습니다. p가
    {{ percent(f.pairBreakEven) }}를 넘는 것은 풀이 줄었을 때뿐입니다. 상점 레벨에 따라 영웅
    {{ f.pairPool.low }}~{{ f.pairPool.high }}명 이하로 줄어야 하며, 예를 들어 많은 영웅이 신화
    등급이 된 경우입니다. 그때는 새로고침이 낫습니다. 최고 확률 기준으로는 사면 바로 목표를 이루므로
    삽니다.
  </p>

  <h3>관찰 4. 영웅 한 명을 찾을 때는 한 장짜리 영웅 카드가 무작위 팩이나 진영 팩보다 낫다</h3>
  <p>
    한 장짜리 영웅 카드는 휘장 {{ f.heroPrice }}개로 원하는 영웅 한 장을 확실히 줍니다. 팩은 풀에서
    중복을 허용해 영웅 {{ f.draws }}명을 뽑으므로, 풀의 영웅이 n명, 그중 원하는 영웅이 k명이면
    원하는 영웅을 평균 {{ f.draws }} × k ÷ n장 줍니다. 팩의 가격을 c라고 하면, 다음 조건에서는
    팩으로 얻는 한 장의 비용이 카드보다 싸지 않습니다.
  </p>
  <p class="formula">
    c × n ÷ ({{ f.draws }} × k) ≥ {{ f.heroPrice }}, 즉 k ÷ n ≤ c ÷ {{ f.draws * f.heroPrice }}
  </p>
  <p>
    원하는 영웅이 한 명일 때 한 장의 비용은 무작위 팩으로는 휘장
    {{ f.randomPrice / f.draws }} × n개, 영웅이 m명인 진영의 팩으로는
    {{ f.factionPrice / f.draws }} × m개입니다. 풀이 {{ f.poolSize }}명, 진영이
    {{ f.factionPoolSize }}명이면 각각 {{ Math.round(f.copyCost.random) }}개와
    {{ Math.round(f.copyCost.faction) }}개로, 카드의 {{ f.heroPrice }}개보다 훨씬 많습니다. 팩이 한
    장짜리 영웅 카드보다 나은 것은 원하는 영웅이 풀에서 큰 비중을 차지할 때뿐입니다. 무작위 팩은
    풀의 {{ percent(f.packShare.random) }}, 진영 팩은 그 진영의 {{ percent(f.packShare.faction) }}를
    넘어야 합니다. 팩에서 나온 영웅을 모두 팔아도 돌려받는 휘장은 최대 {{ f.packRefund }}개이므로,
    원하는 영웅이 한 명일 때 결론은 바뀌지 않습니다.
  </p>

  <h3>관찰 5. 영웅 한 명을 찾을 때는 진영 팩이 무작위 팩보다 낫다</h3>
  <p>
    팩의 공식에 따라 팩 하나에서 그 영웅이 나올 확률은 1 − (1 − 1 ÷ n)<sup>{{ f.draws }}</sup
    >입니다. 나올 때까지 같은 팩을 산다면 평균 비용은 가격을 이 확률로 나눈 값입니다. 그 영웅의
    진영에 영웅이 m명, 전체 풀에 n명 있을 때 두 팩을 비교하면:
  </p>
  <p class="formula">
    {{ f.factionPrice }} ÷ (1 − (1 − 1 ÷ m)<sup>{{ f.draws }}</sup
    >) 대 {{ f.randomPrice }} ÷ (1 − (1 − 1 ÷ n)<sup>{{ f.draws }}</sup
    >)
  </p>
  <p>
    진영이 {{ f.factionPoolSize }}명, 풀이 {{ f.poolSize }}명이면 진영 팩은 휘장 약
    {{ Math.round(f.packCost.faction) }}개, 무작위 팩은 약 {{ Math.round(f.packCost.random) }}개가
    듭니다. 확률이 작을 때 이 확률은 {{ f.draws }} ÷ x에 가까우므로, 비교는 대략
    {{ f.factionPrice / f.draws }} × m 대 {{ f.randomPrice / f.draws }} × n입니다. 둘은 전체 풀이 그
    영웅 진영의 약 두 배일 때 같아집니다. 진영이 {{ f.factionPoolSize }}명이면 약
    {{ Math.round(f.packPool) }}명입니다.
  </p>
  <p>
    네 진영에 남은 영웅 수가 비슷한 동안에는 진영 팩이 항상 낫습니다. 다른 진영의 영웅이 많이 풀에서
    빠져(예: 신화 등급) 풀이 그 크기보다 작아지면 무작위 팩이 낫습니다. 서로 다른 진영의 여러 영웅
    중 아무나 나와도 된다면 무작위 팩이 더 자주 맞으므로, 이때는 두 팩을 직접 비교해야 합니다.
  </p>
  <p class="reading-secondary">
    규칙은 모든 경우에 성립하므로 언제나 쓸 수 있습니다. 관찰은 그 근거의 조건이 맞을 때만 씁니다.
    풀의 크기, 원하는 영웅의 수, 한 번에 여러 장을 주는 상품이 나올 수 있는지가 그 조건입니다.
    그렇지 않으면 계산으로 정해야 합니다.
  </p>

  <h2>확률의 출처</h2>
  <p>
    게임 밖에서는 아무도 출처를 볼 수 없습니다. Toto가 새로고침마다 상점을 기록하고 그 기록에서
    목록을 추정했습니다. 방법은 최대가능도 추정으로, 기록된 상점들이 나올 가능성이 가장 높아지는
    확률을 고르는 것입니다.
  </p>
  <p>
    카드마다 출처가 표시된다면 추정은 단순한 계산입니다. 한 출처가 N번 뽑아 상품 k가 n<sub>k</sub>번
    나왔다면:
  </p>
  <p class="formula">p<sub>k</sub> ≈ n<sub>k</sub> ÷ N</p>
  <p>
    출처는 숨겨져 있으므로, 상품의 전체 횟수를 새로고침 횟수의 여덟 배로 나누면 합쳐진 빈도만 나올
    뿐 출처별 목록은 알 수 없습니다. 기록에는 전체 횟수 말고도 어떤 상품이 함께 나왔는지, 한 상점에
    몇 장씩 나왔는지가 담겨 있습니다. 같은 상점 레벨의 잠금 없는 상점에 대해, 한 상점에 나온 상품별
    장수를 c, 그 조합이 기록된 상점 수를 n<sub>c</sub>라고 합시다. 추정값은 아래 합을 가장 크게
    만드는 목록 θ입니다.
  </p>
  <p class="formula">Σ<sub>c</sub> n<sub>c</sub> × log P<sub>θ</sub>(c)</p>
  <p>
    출처들이 서로 독립적으로 뽑는다면, 조합 c의 확률은 여덟 출처가 그 조합을 만들 수 있는 모든
    경우의 확률을 더한 값입니다. A(c)는 그 경우들의 집합이고, p<sub>j,z</sub>는 출처 j가 그 경우에
    맡은 상품 z를 낼 확률입니다.
  </p>
  <p class="formula">
    P<sub>θ</sub>(c) = Σ<sub>z ∈ A(c)</sub> p<sub>1,z<sub>1</sub></sub> × p<sub
      >2,z<sub>2</sub></sub
    >
    × … × p<sub>8,z<sub>8</sub></sub>
  </p>
  <p>모든 확률은 0 이상이고, 한 출처의 확률을 모두 더하면 1입니다.</p>
