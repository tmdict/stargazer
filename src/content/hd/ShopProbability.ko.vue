  <h3>최고 확률</h3>
  <p>최고 확률은 가진 휘장으로 이번 라운드에 목표를 이룰 확률을 묻습니다.</p>
  <p class="formula">V(s) = max<sub>a</sub> Σ<sub>o</sub> P(o | s, a) × V(s′)</p>
  <p>
    상태 s는 아직 필요한 장수, 휘장, 보이는 카드, 그리고 그 출처에 대해 알고 있는 내용입니다. a는
    휘장으로 치를 수 있는 수, o는 그 수에서 나올 수 있는 결과 하나, s′은 그 뒤의 상태입니다. 목표를
    이루면 가치는 1이고, 치를 수 있는 수가 하나도 없으면 0입니다. 구매나 새로고침의 결과마다 그 뒤의
    가장 좋은 수를 따라가 확률로 가중합니다. 이를 모두 더하는 것이 전확률의 법칙입니다.
  </p>
  <p>
    그래서 확실한 카드를 먼저 사는 것이 항상 최선은 아닙니다. 지금 한 장짜리 영웅 카드를 사는 것보다
    휘장을 아껴 새로고침한 뒤 두 장짜리 영웅 카드를 사는 편이 나을 수 있습니다.
  </p>

  <h3>최소 휘장</h3>
