  </p>

  <h3>观察 4：只找一位英雄时，单张英雄卡胜过随机卡包和阵营卡包</h3>
  <p>
    单张英雄卡以 {{ f.heroPrice }} 枚徽章确定给出一张想要的英雄。卡包从英雄池中可重复地抽取
    {{ f.draws }} 位，池中有 n 位英雄、其中 k 位是想要的，平均给出 {{ f.draws }} × k ÷ n
    张想要的英雄。设卡包价格为 c，在以下条件下，通过卡包得到一张的花费不低于单张英雄卡：
  </p>
  <p class="formula">
    c × n ÷ ({{ f.draws }} × k) ≥ {{ f.heroPrice }}，即 k ÷ n ≤ c ÷ {{ f.draws * f.heroPrice }}
  </p>
  <p>
    只想要一位英雄时，通过随机卡包每张要花 {{ f.randomPrice / f.draws }} × n 枚徽章，通过有 m
    位英雄的阵营的卡包每张要花 {{ f.factionPrice / f.draws }} × m 枚。英雄池有
    {{ f.poolSize.value }} 位、阵营有 {{ f.factionPoolSize.value }} 位时，分别是
    {{ Math.round(f.copyCost.value.random) }} 枚和
    {{ Math.round(f.copyCost.value.faction) }} 枚，远高于单张英雄卡的
    {{
      f.heroPrice
    }}
    枚。只有想要的英雄在池中占很大比例时，卡包才胜过单张英雄卡：随机卡包要超过英雄池的
    {{ percent(f.packShare.random) }}，阵营卡包要超过该阵营的
    {{ percent(f.packShare.faction) }}。卖掉卡包开出的全部英雄最多返还
    {{ f.packRefund }} 枚徽章，所以只想要一位英雄时结论不变。
  </p>

  <h3>观察 5：只找一位英雄时，阵营卡包胜过随机卡包</h3>
  <p>
    按卡包的公式，一个卡包开出该英雄的概率是 1 − (1 − 1 ÷ n)<sup>{{ f.draws }}</sup
    >。一直买同一种卡包直到抽中，平均花费就是价格除以这个概率。设该英雄的阵营有 m
    位英雄，整个英雄池有 n 位，两种卡包的比较是：
  </p>
  <p class="formula">
    {{ f.factionPrice }} ÷ (1 − (1 − 1 ÷ m)<sup>{{ f.draws }}</sup
    >) 对比 {{ f.randomPrice }} ÷ (1 − (1 − 1 ÷ n)<sup>{{ f.draws }}</sup
    >)
  </p>
  <p>
    阵营有 {{ f.factionPoolSize.value }} 位、英雄池有 {{ f.poolSize.value }} 位时，阵营卡包约需
    {{ Math.round(f.packCost.value.faction) }} 枚徽章，随机卡包约需
    {{ Math.round(f.packCost.value.random) }} 枚。概率很小时，这个概率接近 {{ f.draws }} ÷
    x，所以比较大致是 {{ f.factionPrice / f.draws }} × m 对 {{ f.randomPrice / f.draws }} ×
    n。两者在整个英雄池约为该阵营两倍时持平：阵营有 {{ f.factionPoolSize.value }} 位时，约为
    {{ Math.round(f.packPool.value) }} 位。
  </p>
  <p>
    四个阵营剩下的英雄数相近时，阵营卡包总是更好。如果其他阵营的许多英雄已离开英雄池（例如达到神话），使英雄池小于这个数，随机卡包更好。想要的几位英雄分属不同阵营、得到任意一位即可时，随机卡包抽中的概率更高，这时应直接比较两种卡包。
  </p>
  <p class="reading-secondary">
    规则在任何情况下都成立，随时可用。观察只在其推理的条件成立时使用：英雄池的大小、想要的英雄数、是否可能出现一次给出多张的商品。否则需要通过计算来决定。
  </p>

  <h2>概率从何而来</h2>
  <p>
    游戏之外没有人能看到来源。Toto
    逐次记录了刷新出的商店，并据此推算出各来源的清单。方法是最大似然估计：选出让记录到的商店最有可能出现的那组概率。
  </p>
  <p>
    如果每张卡片都标明来源，估计值就是简单的计数。某个来源抽取 N 次，其中商品 k 出现 n<sub>k</sub>
    次：
  </p>
  <p class="formula">p<sub>k</sub> ≈ n<sub>k</sub> ÷ N</p>
  <p>
    来源是隐藏的，所以用某种商品的总数除以“刷新次数 ×
    8”，得到的只是合并后的频率，而不是每个来源的清单。记录里不只有总数，还有哪些商品同时出现、一个商店里各出现几张。对同一商店等级下没有锁定的商店，设
    c 为一个商店中各商品的张数，n<sub>c</sub>
    为记录中出现这种张数组合的商店数。估计值是使下面的和最大的那组清单 θ：
  </p>
  <p class="formula">Σ<sub>c</sub> n<sub>c</sub> × log P<sub>θ</sub>(c)</p>
  <p>
    来源各自独立抽取时，组合 c 的概率是八个来源产出它的每种方式的概率之和。A(c)
    是这些方式的集合，p<sub>j,z</sub>
    是来源 j 产出其中分配给它的商品 z 的概率：
  </p>
  <p class="formula">
    P<sub>θ</sub>(c) = Σ<sub>z ∈ A(c)</sub> p<sub>1,z<sub>1</sub></sub> × p<sub
      >2,z<sub>2</sub></sub
    >
    × … × p<sub>8,z<sub>8</sub></sub>
  </p>
  <p>每个概率都不小于 0，同一个来源的概率之和为 1。</p>
  <ul>
    <li>
      保留下来的卡片不是新抽取的。一条记录只统计新抽出的卡片，并结合刷新前的锁定状态以及这些锁定卡片可能占用的来源来解读。刷新之后才加上的锁定属于下一次刷新。把保留的卡片当作新抽取来统计，会使估计产生偏差。
    </li>
    <li>实测数值旁的范围是 95% 的范围，通过多次有放回地随机重抽记录并重复估计得出。</li>
    <li>
      每个来源能产出哪些商品，也是从记录中推算的。范围是在这一点固定的前提下，只反映概率可能的偏差。
    </li>
  </ul>
