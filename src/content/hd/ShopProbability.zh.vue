    {{ f.heroPrice }} 枚的单张英雄卡。设一次刷新出现这张单卡的概率为 p，大约需要刷新 1 ÷ p
    次，所以在以下条件下，等待的平均花费更高：
  </p>
  <p class="formula">
    {{ f.heroPrice }} + {{ f.reroll }} ÷ p ≥ {{ f.pairPrice }}，即 p ≤
    {{ percent(f.pairBreakEven) }}
  </p>
  <p>
    每次刷新面对的都是同样的选择，所以先刷几次再买不会比两者中较好的那个更好。根据观察
    4，卡包不会改变这个比较。在会出现双张英雄卡的商店等级，英雄池为全部
    {{ f.poolSize.value }} 位时，p 在 {{ percent(f.pairSingle.value.low) }} 到
