      {{ f.legendaryCopies }} 张，都是同一位英雄。
    </li>
    <li>标记为已购买的卡片不会从所需张数中扣除。请按实际购买之后还缺的张数填写。</li>
    <li>最高概率是本回合结束前拿到目标的概率，不是它在下一个商店里出现的概率。</li>
    <li>
      “只买现有商品”是完全不刷新时的概率：在已输入的卡片中选出最好的购买组合，徽章够的话可以买多个卡包。
    </li>
  </ul>

  <h3>最高概率</h3>
  <p>最高概率问的是：用手上的徽章，本回合达成目标的概率有多大。</p>
  <p class="formula">V(s) = max<sub>a</sub> Σ<sub>o</sub> P(o | s, a) × V(s′)</p>
  <p>
    状态 s 包含还需要的张数、徽章、商店里的卡片，以及对它们来源的了解。a 是付得起的一步，o
    是这一步可能带来的一种结果，s′ 是之后的状态。达成目标的价值是 1，没有任何付得起的走法时价值是
    0。购买或刷新的每种结果都按它之后的最优走法计算，再按概率加权。把它们加起来，就是全概率公式。
  </p>
  <p>
    所以确定能买到的卡片不一定是第一步。现在买下一张单张英雄卡，可能不如把徽章留着，刷新后买双张英雄卡。
  </p>

  <h3>最少徽章</h3>
  <p>最少徽章问的是：如果可以一直刷新，达成目标平均要花多少徽章。</p>
  <p class="formula">E(s) = min<sub>a</sub> [ c(a) + Σ<sub>o</sub> P(o | s, a) × E(s′) ]</p>
  <p>
    E(s) 是从状态 s
    到达成目标平均花费的徽章数。这里的状态包含还需要的张数、商店里的卡片，以及对锁定卡片来源的了解，但不包含持有的徽章。c(a)
    是一步的花费：刷新是 {{ f.reroll }}
    枚徽章，购买是商品的价格。出售卡包英雄得到的徽章按每种结果分别扣除。达成目标后 E 为 0。
  </p>
  <p>
    没有锁定时，一次刷新可能回到完全相同的状态，所以 E(s)
    同时出现在等式的两边。答案就是让每个状态的等式同时成立的那组数值。没有锁定且只找一张卡片时（出现概率为
    q，价格为 p），它就简化为上面的公式：
  </p>
  <p class="formula">E = {{ f.reroll }} ÷ q + p</p>
  <p>
    随机传说英雄每 {{ f.poolSize.value }} 次才有一次是你要的英雄，所以平均要花
    {{ f.legendaryPrice }} × {{ f.poolSize.value }} =
    {{ (f.legendaryPrice * f.poolSize.value).toLocaleString('en') }}
    枚徽章才能抽中一次。只找一位英雄时，最少徽章不会选它。
  </p>
  <p>
    两个答案可能不同。现在买下一张单卡也许是本回合概率最高的一步，而把徽章留到之后的商店平均花费更少。平均值也只是平均值：运气不好时，实际花费可能高得多。
  </p>

  <h2>本回合何时停手</h2>
  <p>
    荣誉对决要打多个回合，留下的徽章会在之后的商店里用掉。最高概率只看本回合。最少徽章看的是达成目标的整个过程：徽章没有上限时，任何方案最终都能达成，所以应选平均花费最少的方案。
  </p>
  <p>
    徽章无限只是用来比较选择的假设。实际只能用手上的徽章，所以本回合已经无法达成目标时，停手比继续花徽章更好。每个回合的第一个商店会免费重新抽取未锁定的卡片，所以停手之后不用花刷新的徽章就能看到新的商店。
  </p>
  <p>
    计算器在以下情况建议停手：最省的一步付不起；这一步之后本回合已无法达成；或下一回合商店等级提升，且等待比现在省下的徽章多于一次刷新。
  </p>
  <p>
    停手之前是锁定还是买下一张卡片，也用同一个等式判断。锁定可以把好卡留到下一回合，但它的来源不再重新抽取。买下可以空出这个来源，但即使之后出现更好的卡片，徽章也已经花掉了。下一回合商店等级提升时，来源产出的商品会变，所以要按那个等级的清单来判断锁定或购买的价值。
  </p>
  <p>
    徽章充足时，最高概率和最少徽章通常给出同一步。徽章紧张时两者可能不同：如果本回合只剩一个
    {{ f.draws }}
    位英雄的卡包能凑齐两张，最高概率会买下它，而最少徽章会放弃这个不划算的卡包并停手，留到之后的回合找英雄卡。
  </p>

  <h2>规则与观察</h2>
  <p>
    规则是在任何情况下都成立的比较。一种选择永远不比另一种差时，就不必再考虑另一种。观察是带条件的比较，通过比较平均徽章或概率得出。条件成立时它可以指导决定，条件不成立时结论可能相反，所以它不能代替计算。
  </p>

  <h3>规则 1：反正要买的锁定卡片，现在就买</h3>
  <p>
    锁定的卡片现在买和以后买价格一样，而买下后的空位会在下一次刷新时重新抽取，多一次机会。只有在之后可能放弃这张卡片、用更少的徽章达成时，锁定才比买下更好。锁定的价值就在于可以放弃，这个价值是否超过多出来的一次抽取，要靠计算判断。
  </p>

  <h3>规则 2：同一个商店里既要买卡包又要买确定的卡片时，先开卡包</h3>
  <p>
    在同一个商店里，购买顺序不影响价格，卡片在下一次刷新前也不会消失。先开结果不确定的卡包，就能在看到结果后再决定其余的购买。卡包开出了目标英雄，确定的那张卡片就不用买了。先开卡包永远不会更差。
  </p>

  <h3>观察 1：买下不会造成多买时，直接买，不要锁定</h3>
  <p>
    英雄卡每张 {{ f.heroPrice }}
    枚徽章，单张卡和双张卡都一样。锁定通常是为了避免多买。还需要两张时，买下一张单张英雄卡后，之后出现的双张英雄卡就等于买了三张；而把单张英雄卡锁定，就可以买双张英雄卡并放弃锁定的那张。
  </p>
  <p>
    只有还需要的张数是奇数、并用双张英雄卡补齐时才会多买。买双张英雄卡不会改变所需张数的奇偶，所需张数是奇数时买一张单张英雄卡会让它变成偶数，风险就消失了。这些情况下，不买这张卡片能达成的任何方式，买下之后同样能达成，花费也不会更高，所以没有理由放弃它。
  </p>
  <p>
    如果可能出现一次给出多张的商品，例如一次给 {{ f.legendaryCopies }}
    张的随机传说英雄，每张的价格就不再相同，这条观察不成立。
  </p>

  <h3>观察 2：需要两张时，徽章紧张就锁定单张英雄卡，徽章充足就买下</h3>
  <p>
    这是多买影响最大的情况。设持有 B 枚徽章，商店里有一张单张英雄卡。锁定它时，无论怎样达成都要花
    {{ f.pairPrice }}
    枚徽章：再来一张单张英雄卡加上锁定的那张，或者买双张英雄卡并放弃锁定的那张。可用于刷新的次数是
    (B − {{ f.pairPrice }}) ÷ {{ f.reroll }}。
  </p>
  <p>
    立即买下时，如果最后一张来自单张英雄卡，可刷新次数相同；如果来自双张英雄卡，就只有 (B −
    {{ f.heroPrice + f.pairPrice }}) ÷ {{ f.reroll }} 次，少了
    {{ f.heroPrice / f.reroll }}
    次。作为交换，买下后的空位每次刷新都会重新抽取。徽章少时，这
    {{ f.heroPrice / f.reroll }}
    次刷新占比很大，锁定更好；徽章多时，通常在用到它们之前就已达成，多出来的抽取更有价值。
  </p>
  <p>
    按 Toto 的计算器，在商店等级 {{ f.levels.length }}、英雄池为全部
    {{ f.poolSize.value }} 位时，分界点约为 60
    枚徽章：低于它锁定更好，高于它买下更好，分界点附近两者相差不到 1
    个百分点。在更低的等级，双张英雄卡很少见，即使徽章少也是买下更好。这里比较的是本回合达成目标的概率，没有计入本回合未达成时手里留着这张卡片的价值。
  </p>

  <h3>观察 3：只需要一张而出现该英雄的双张英雄卡时，买下它</h3>
